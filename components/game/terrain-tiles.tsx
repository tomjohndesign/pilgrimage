/** Top of the base slab. Must sit below the shortest terrain height. */
export const SLAB_TOP = 0.08

/** The slab is the block of earth the map sits on; its sides are the cliff. */
const SLAB_THICKNESS = 3.2
/**
 * The slab pokes out slightly past the tiles on every side. This is what kills
 * the z-fighting shimmer along the map edge — tile sides would otherwise be
 * exactly coplanar with the slab's sides — and it reads as a lip of dirt that
 * the turf sits on.
 */
const SLAB_EXPAND = 0.1
/** Generated by scripts/generate-dirt-texture.mjs. */
const DIRT_TEXTURE_URL = "/textures/dirt-side.png"

/**
 * The optional grid is one global lattice projected onto the terrain, not a
 * border on each tile. The shader darkens a band this wide (in world units) on
 * either side of every integer world-space line on the tiles' top faces, so
 * the lines run continuously across the map and never depend on the
 * individual boxes under them.
 */
const GRID_HALF_WIDTH = 0.025
/** How much a grid line darkens the tile colour underneath it. */
const GRID_DARKEN = 0.8

/**
 * Anchor tints for the forest-shade gradient. Every tile's colour is pulled
 * (by its terrain's `shadeBlend`) toward a point on the ramp between these two,
 * chosen by how deep in the woods it sits — so the ground darkens under the
 * forest cluster and brightens continuously toward open meadow, instead of
 * snapping between two flat greens at the tree line.
 */
const DEEP_WOOD_TINT = new THREE.Color("#36452a")
const OPEN_MEADOW_TINT = new THREE.Color("#94a158")

/**
 * The ground darkens by this much more under the heart of a dark forest.
 * Unlike the forest-shade tint this ignores `shadeBlend`: it is the canopy's
 * shadow, and it falls on the track cut through the old growth just as it
 * falls on the forest floor — a bright ribbon through the dark would lie
 * about how dark it is in there.
 */
const DARK_WOOD_DARKEN = 0.4

/** Generated by scripts/generate-grass-texture.mjs. */
const GRASS_TEXTURE_URL = "/textures/grass.png"
/** Repeats of the grass texture per world unit: one repeat spans three tiles. */
const GRASS_UV_SCALE = 1 / 3
/**
 * Which ground wears the grass texture, and how strongly the tile's own colour
 * is laid over the sward first. Clear land *is* the sward — its colour is the
 * texture's average, so there is nothing to lay over. The forest floor is the
 * same grass with the forest colour over it, dark under the canopy but with
 * the mottle still showing through so the tree line reads as shaded meadow
 * rather than a change of material; clearings sit between. Everything else
 * (bare earth, the track, hills) keeps its flat colour.
 */
const SWARD_OVERLAY: Partial<Record<TerrainId, number>> = {
  grass: 0,
  clearing: 0.5,
  forest: 0.7,
}

/**
 * Repeats of the road texture per world unit. Road tops are UV-mapped by world
 * position, so the surface runs continuously from tile to tile — a cobble can
 * straddle a tile boundary — and the seams never line up with the grid. One
 * repeat spans two tiles.
 */
const ROAD_UV_SCALE = 0.5

/** What the road's (rarely visible) sides wear instead of the top texture. */
const ROAD_SIDE_COLOR = "vec3(0.62, 0.51, 0.37)"

/**
 * How deep the ragged verge bites into a road tile, in tile units, before the
 * tier's edgeWear scales it. The bite depth is noise over *world* position, so
 * two road tiles eroding the same side always agree at their shared corner and
 * the ragged line runs continuously along the road.
 */
const EDGE_BITE_MIN = 0.06
const EDGE_BITE_MAX = 0.38

/** What a road's surface looks like at one tier, for the road material. */
interface RoadSurface {
  texture: THREE.Texture
  edgeWear: number
  sward: number
}

interface TileMaterialOptions {
  grassTexture: THREE.Texture
  /**
   * Lattice origin for the optional grid overlay. Tile boundaries sit at
   * `k - width/2` in world units, so this shifts the lattice to land on them
   * for any map size. Omit for no grid.
   */
  gridOrigin?: { x: number; z: number }
  road?: RoadSurface
}

/**
 * A Lambert material for the ground boxes, with the surfaces painted in the
 * shader from world-space XZ so nothing repeats per tile: `normal.y` picks out
 * the top face, and fwidth-based smoothing keeps every edge from shimmering at
 * far zooms.
 *
 * Every tile carries a per-instance `aGrass` weight and an `aOverlay` colour.
 * On plain ground `aGrass` flags sward tiles, whose tops wear the grass
 * texture (the instance colour is white there, so the texture carries the
 * colour) with `aOverlay` laid over it — the tile's own colour and the
 * forest-shade ramp, folded into one tint and opacity. Both textures go
 * through `sampleTiled`, which blends two offset copies by slow world noise
 * so neither texture's repeat ever shows.
 *
 * With `road` set, the top face is instead textured with the road surface,
 * multiplied by the per-instance weathering tint (see roadTint). Grass
 * reclaims the surface wherever world-space noise says so — the tier's
 * `sward` sets how much, and `aGrass` (how much grass hems the tile in, see
 * roadEdge) pushes it further — and a noise-eaten verge margin creeps in
 * along the sides flagged open in `aRoadOpen`, wearing `aVergeColor` (or the
 * grass texture, by its `w`), so the road never sits perfectly square. The
 * shade ramp then lands on the road through `aOverlay` like any other tile.
 *
 * With `gridOrigin` set, the global grid lattice is drawn on top.
 */
function makeTileMaterial({
  grassTexture,
  gridOrigin,
  road,
}: TileMaterialOptions): THREE.MeshLambertMaterial {
  const material = new THREE.MeshLambertMaterial()
  material.onBeforeCompile = (shader) => {
    shader.uniforms.grassMap = { value: grassTexture }
    shader.uniforms.grassFlat = { value: new THREE.Color(TERRAIN.grass.color) }
    if (road) {
      shader.uniforms.roadMap = { value: road.texture }
      shader.uniforms.roadEdgeWear = { value: road.edgeWear }
      shader.uniforms.roadSward = { value: road.sward }
    }
    shader.vertexShader = shader.vertexShader
      .replace(
        "#include <common>",
        `varying vec2 vWorld;
        varying float vGridTop;
        attribute float aGrass;
        attribute vec4 aOverlay;
        varying float vGrass;
        varying vec4 vOverlay;
        #ifdef USE_ROAD_MAP
          attribute vec4 aRoadOpen;
          attribute vec4 aVergeColor;
          varying vec4 vRoadOpen;
          varying vec4 vVergeColor;
          varying vec2 vTileLocal;
        #endif
        #include <common>`,
      )
      .replace(
        "#include <project_vertex>",
        `#include <project_vertex>
        {
          vec4 worldPos = vec4(transformed, 1.0);
          #ifdef USE_INSTANCING
            worldPos = instanceMatrix * worldPos;
          #endif
          worldPos = modelMatrix * worldPos;
          vWorld = worldPos.xz;
          vGridTop = step(0.5, normal.y);
          vGrass = aGrass;
          vOverlay = aOverlay;
          #ifdef USE_ROAD_MAP
            vRoadOpen = aRoadOpen;
            vVergeColor = aVergeColor;
            // Tile-local XZ in *world* axes, so an instance yawed to face
            // its bridge (a ramp) still lines its edge data up with the map.
            #ifdef USE_INSTANCING
              vTileLocal = (instanceMatrix * vec4(position.x, 0.0, position.z, 0.0)).xz + 0.5;
            #else
              vTileLocal = position.xz + 0.5;
            #endif
          #endif
        }`,
      )
    shader.fragmentShader = shader.fragmentShader
      .replace(
        "#include <common>",
        `varying vec2 vWorld;
        varying float vGridTop;
        varying float vGrass;
        varying vec4 vOverlay;
        uniform sampler2D grassMap;
        uniform vec3 grassFlat;
        #ifdef USE_ROAD_MAP
          uniform sampler2D roadMap;
          uniform float roadEdgeWear;
          uniform float roadSward;
          varying vec4 vRoadOpen;
          varying vec4 vVergeColor;
          varying vec2 vTileLocal;
        #endif
        float tileHash(vec2 p) {
          return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453);
        }
        float tileNoise(vec2 p) {
          vec2 i = floor(p);
          vec2 f = fract(p);
          f = f * f * (3.0 - 2.0 * f);
          return mix(
            mix(tileHash(i), tileHash(i + vec2(1.0, 0.0)), f.x),
            mix(tileHash(i + vec2(0.0, 1.0)), tileHash(i + vec2(1.0, 1.0)), f.x),
            f.y
          );
        }
        // A seamless texture still repeats: sample it twice, the second copy
        // turned and rescaled so its repeats never line up with the first,
        // and let slow world noise pick between them.
        vec3 sampleTiled(sampler2D map, vec2 uv, vec2 world) {
          vec3 a = texture2D(map, uv).rgb;
          vec3 b = texture2D(map, mat2(0.6, 0.8, -0.8, 0.6) * uv * 0.83 + vec2(0.37, 0.61)).rgb;
          float pick = tileNoise(world * 0.31) * 0.7 + tileNoise(world * 1.1) * 0.3;
          return mix(a, b, smoothstep(0.35, 0.65, pick));
        }
        #include <common>`,
      )
      .replace(
        "#include <color_fragment>",
        `#include <color_fragment>
        {
          vec2 world = vWorld;
          vec3 grassColor = sampleTiled(grassMap, world * ${GRASS_UV_SCALE}, world);
          #ifdef USE_ROAD_MAP
            vec3 roadColor = sampleTiled(roadMap, world * ${ROAD_UV_SCALE}, world);

            // Sward: world-space noise says where the grass has reclaimed the
            // surface, so the patches never repeat with the texture and run
            // straight across tile boundaries. The tier sets how much of the
            // road is lost to it; grass hemming the tile in pushes it further.
            // Summed value noise bunches around 0.5; the smoothstep spreads it
            // back out so roadSward reads roughly as a share of the surface.
            float sward = smoothstep(0.25, 0.75,
              tileNoise(world * 0.7) * 0.5 + tileNoise(world * 1.9) * 0.3 + tileNoise(world * 5.3) * 0.2);
            float reclaim = roadSward * (0.6 + 0.8 * vGrass);
            float cover = smoothstep(1.0 - reclaim - 0.08, 1.0 - reclaim + 0.08, sward);
            roadColor = mix(roadColor, grassColor, cover);
            vec3 surface = mix(${ROAD_SIDE_COLOR}, roadColor, vGridTop);

            // Ragged verge: noise over world position decides how deep the
            // land bites into this tile from each open side. World-space noise
            // keeps the ragged line continuous across tile boundaries.
            float bite = roadEdgeWear *
              (${EDGE_BITE_MIN} + (${EDGE_BITE_MAX} - ${EDGE_BITE_MIN}) *
                (tileNoise(world * 3.7) * 0.65 + tileNoise(world * 8.3) * 0.35));
            float d = 1.0;
            d = min(d, mix(1.0, 1.0 - vTileLocal.x, vRoadOpen.x));
            d = min(d, mix(1.0, vTileLocal.x, vRoadOpen.y));
            d = min(d, mix(1.0, 1.0 - vTileLocal.y, vRoadOpen.z));
            d = min(d, mix(1.0, vTileLocal.y, vRoadOpen.w));
            float vergeAa = max(fwidth(d) * 1.5, 0.008);
            float verge = (1.0 - smoothstep(bite - vergeAa, bite + vergeAa, d)) * vGridTop;
            vec3 vergeFlat = vVergeColor.rgb * (0.85 + 0.3 * tileNoise(world * 9.1));
            vec3 vergeColor = mix(vergeFlat, grassColor, vVergeColor.w);
            surface = mix(surface, vergeColor, verge);
            diffuseColor.rgb *= mix(surface, vOverlay.rgb, vOverlay.a);
          #else
            // Sward tiles: the texture on top, the flat grass colour on the
            // sides, the tile's own tint laid over both.
            vec3 top = mix(grassColor, vOverlay.rgb, vOverlay.a);
            vec3 side = mix(grassFlat, vOverlay.rgb, vOverlay.a);
            diffuseColor.rgb *= mix(vec3(1.0), mix(side, top, vGridTop), vGrass);
          #endif
          #ifdef USE_GRID
            // Distance to the nearest lattice line along each axis.
            vec2 cell = fract(world + vec2(${(gridOrigin?.x ?? 0).toFixed(3)}, ${(gridOrigin?.z ?? 0).toFixed(3)}));
            vec2 axisDist = 0.5 - abs(cell - 0.5);
            float gridDist = min(axisDist.x, axisDist.y);
            float aa = fwidth(gridDist);
            float line = (1.0 - smoothstep(${GRID_HALF_WIDTH} - aa, ${GRID_HALF_WIDTH} + aa, gridDist)) * vGridTop;
            diffuseColor.rgb *= mix(1.0, ${GRID_DARKEN}, line);
          #endif
        }`,
      )
  }
  material.defines = {
    ...(road ? { USE_ROAD_MAP: "" } : {}),
    ...(gridOrigin ? { USE_GRID: "" } : {}),
  }
  // The grid origin is baked into the shader source, so it has to be part of
  // the program key or two maps of different sizes would share one program.
  const gridKey = gridOrigin ? `${gridOrigin.x.toFixed(3)}:${gridOrigin.z.toFixed(3)}` : "nogrid"
  material.customProgramCacheKey = () => `tiles-${road ? "road" : "ground"}-${gridKey}`
  return material
}

/**
 * Attach the per-instance data makeTileMaterial reads: `aGrass` and
 * `aOverlay` on every tile, plus the edge data (`aRoadOpen`, `aVergeColor`)
 * the road's erosion shader needs.
 */
function addTileAttributes(geometry: THREE.BufferGeometry, slots: number, road: boolean): void {
  const n = Math.max(1, slots)
  geometry.setAttribute("aGrass", new THREE.InstancedBufferAttribute(new Float32Array(n), 1))
  geometry.setAttribute("aOverlay", new THREE.InstancedBufferAttribute(new Float32Array(n * 4), 4))
  if (road) {
    geometry.setAttribute("aRoadOpen", new THREE.InstancedBufferAttribute(new Float32Array(n * 4), 4))
    geometry.setAttribute("aVergeColor", new THREE.InstancedBufferAttribute(new Float32Array(n * 4), 4))
  }
}

/** Unit box for flat tiles, with the per-instance tile data. */
function makeTileGeometry(slots: number, road = false): THREE.BoxGeometry {
  const geometry = new THREE.BoxGeometry(1, 1, 1)
  addTileAttributes(geometry, slots, road)
  return geometry
}

/**
 * The ramp up onto a bridge: a tile-sized wedge with its base on y=0, rising
 * from ground level at its -x edge to deck level at its +x edge; instances
 * are yawed to face their bridge. Every face stays planar, so the box's
 * per-face normals recompute cleanly, and the sloped top still counts as a
 * top face in the shader (its normal is well above the 0.5 cut-off).
 */
function makeRampGeometry(slots = 0, road = false): THREE.BoxGeometry {
  const geometry = new THREE.BoxGeometry(1, 1, 1)
  const position = geometry.getAttribute("position") as THREE.BufferAttribute
  for (let i = 0; i < position.count; i++) {
    const top = position.getY(i) > 0
    position.setY(i, top ? TILE_HEIGHT + BRIDGE_RISE * (position.getX(i) + 0.5) : 0)
  }
  position.needsUpdate = true
  geometry.computeVertexNormals()
  addTileAttributes(geometry, slots, road)
  return geometry
}

/**
 * Chebyshev distance (1 or 2) from a tile to the nearest water-bearing tile,
 * or 3 when none is that close. Bridges count — the water still runs under
 * them. Drives the sand-to-grass fade on beach tiles.
 */
function waterDistance(map: GameMap, x: number, z: number): number {
  const wet = (wx: number, wz: number) => {
    if (wx < 0 || wz < 0 || wx >= map.width || wz >= map.depth) return false
    const i = wz * map.width + wx
    return map.water ? map.water.depth[i] > 0 : map.tiles[i] === "water"
  }
  for (let r = 1; r <= 2; r++) {
    for (let dz = -r; dz <= r; dz++) {
      for (let dx = -r; dx <= r; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dz)) !== r) continue
        if (wet(x + dx, z + dz)) return r
      }
    }
  }
  return 3
}

export function TerrainTiles({
  map,
  roadTier = DEFAULT_ROAD_TIER,
  showGrid = false,
}: {
  map: GameMap
  /** Road development tier — index into ROAD_TIERS. */
  roadTier?: number
  /** Draw the global tile lattice over the ground. Off by default. */
  showGrid?: boolean
}) {
  const groundMeshRef = useRef<THREE.InstancedMesh>(null)
  const roadMeshRef = useRef<THREE.InstancedMesh>(null)
  const groundRampMeshRef = useRef<THREE.InstancedMesh>(null)
  const roadRampMeshRef = useRef<THREE.InstancedMesh>(null)
  const idMeshRef = useRef<THREE.InstancedMesh>(null)
  const idRampMeshRef = useRef<THREE.InstancedMesh>(null)
  const count = map.width * map.depth

  const tier = ROAD_TIERS[clampRoadTier(roadTier)]
  const roadCount = useMemo(
    () => map.tiles.reduce((n, t) => (t === "path" ? n + 1 : n), 0),
    [map],
  )

  // All tiers load up front so switching tier swaps textures without a
  // suspend (which would blank the whole terrain for a frame).
  const roadTextures = useLoader(
    THREE.TextureLoader,
    ROAD_TIERS.map((t) => t.textureUrl),
  )
  const grass = useLoader(THREE.TextureLoader, GRASS_TEXTURE_URL)
  useMemo(() => {
    for (const texture of [...roadTextures, grass]) {
      texture.colorSpace = THREE.SRGBColorSpace
      // World-position UVs walk off in every direction, so wrap both axes.
      texture.wrapS = THREE.RepeatWrapping
      texture.wrapT = THREE.RepeatWrapping
      texture.anisotropy = 4
    }
  }, [roadTextures, grass])
  const roadTexture = roadTextures[tier.tier]

  // Tile boundaries sit at integer offsets from -width/2, so the lattice
  // origin is that half-extent modulo one tile.
  const gridOrigin = useMemo(
    () => (showGrid ? { x: (map.width / 2) % 1, z: (map.depth / 2) % 1 } : undefined),
    [showGrid, map.width, map.depth],
  )
  const groundMaterial = useMemo(
    () => makeTileMaterial({ grassTexture: grass, gridOrigin }),
    [grass, gridOrigin],
  )
  useEffect(() => () => groundMaterial.dispose(), [groundMaterial])
  const roadMaterial = useMemo(
    () =>
      makeTileMaterial({
        grassTexture: grass,
        gridOrigin,
        road: { texture: roadTexture, edgeWear: tier.edgeWear, sward: tier.sward },
      }),
    [grass, gridOrigin, roadTexture, tier],
  )
  useEffect(() => () => roadMaterial.dispose(), [roadMaterial])

  const groundGeometry = useMemo(() => makeTileGeometry(count - roadCount), [count, roadCount])
  useEffect(() => () => groundGeometry.dispose(), [groundGeometry])

  // The road's box geometry also carries the per-instance edge data the
  // erosion shader reads: which sides face open land, and what colour that
  // land is (with how much of it is grass in the fourth channel).
  const roadGeometry = useMemo(() => makeTileGeometry(roadCount, true), [roadCount])
  useEffect(() => () => roadGeometry.dispose(), [roadGeometry])

  // Bridge approaches wear the same materials on wedge geometry: one
  // instanced mesh per material, drawn over the flat tile beneath, which the
  // wedge hides entirely (they meet only along the far edge). The ground
  // rises there; the decks themselves are their own component (bridges.tsx).
  const bridges = useMemo(() => bridgeLayout(map), [map])
  const rampAt = useMemo(() => {
    const at = new Map<number, BridgeRamp>()
    for (const ramp of bridges.ramps) at.set(ramp.z * map.width + ramp.x, ramp)
    return at
  }, [bridges, map.width])
  const plateaus = useMemo(
    () => new Set(bridges.plateaus.map((p) => p.z * map.width + p.x)),
    [bridges, map.width],
  )
  const roadRampCount = useMemo(
    () =>
      bridges.ramps.reduce(
        (n, r) => (map.tiles[r.z * map.width + r.x] === "path" ? n + 1 : n),
        0,
      ),
    [bridges, map],
  )
  const groundRampCount = bridges.ramps.length - roadRampCount
  const roadRampGeometry = useMemo(() => makeRampGeometry(roadRampCount, true), [roadRampCount])
  useEffect(() => () => roadRampGeometry.dispose(), [roadRampGeometry])
  const groundRampGeometry = useMemo(() => makeRampGeometry(groundRampCount), [groundRampCount])
  useEffect(() => () => groundRampGeometry.dispose(), [groundRampGeometry])
  const idRampGeometry = useMemo(() => makeRampGeometry(), [])
  useEffect(() => () => idRampGeometry.dispose(), [idRampGeometry])

  useLayoutEffect(() => {
    const groundMesh = groundMeshRef.current
    const roadMesh = roadMeshRef.current
    const groundRampMesh = groundRampMeshRef.current
    const roadRampMesh = roadRampMeshRef.current
    const idMesh = idMeshRef.current
    const idRampMesh = idRampMeshRef.current
    if (!groundMesh || !roadMesh || !groundRampMesh || !roadRampMesh || !idMesh || !idRampMesh) {
      return
    }

    const matrix = new THREE.Matrix4()
    const rampMatrix = new THREE.Matrix4()
    const position = new THREE.Vector3()
    const quaternion = new THREE.Quaternion()
    const rampQuaternion = new THREE.Quaternion()
    const scale = new THREE.Vector3()
    const unit = new THREE.Vector3(1, 1, 1)
    const up = new THREE.Vector3(0, 1, 0)
    const color = new THREE.Color()
    const tint = new THREE.Color()
    const own = new THREE.Color()
    const verge = new THREE.Color()

    // Every tile writes to the flat mesh for its material; a bridge approach
    // writes the same data to that material's ramp mesh as well.
    const attr = (geometry: THREE.BufferGeometry, name: string) =>
      geometry.getAttribute(name) as THREE.InstancedBufferAttribute
    const roadTargets = [roadMesh, roadRampMesh].map((mesh, i) => {
      const geometry = i === 0 ? roadGeometry : roadRampGeometry
      return {
        mesh,
        next: 0,
        open: attr(geometry, "aRoadOpen"),
        verge: attr(geometry, "aVergeColor"),
        grass: attr(geometry, "aGrass"),
        overlay: attr(geometry, "aOverlay"),
      }
    })
    const groundTargets = [groundMesh, groundRampMesh].map((mesh, i) => {
      const geometry = i === 0 ? groundGeometry : groundRampGeometry
      return {
        mesh,
        next: 0,
        grass: attr(geometry, "aGrass"),
        overlay: attr(geometry, "aOverlay"),
      }
    })
    const RAMP = 1

    const grassColor = new THREE.Color(TERRAIN.grass.color)
    const sandColor = new THREE.Color(TERRAIN.sand.color)
    const waterColors = WATER_DEPTH_COLORS.map((c) => new THREE.Color(c))
    // Colour grain is a function of the map's own seed, one stream per consumer.
    // One draw per tile in scan order, whichever mesh the tile lands in, so the
    // grain never reshuffles when the road tier changes.
    const rng = makeRng(deriveSeed(map.seed ?? 0, SEED_STREAM.tileJitter))
    const shade = computeForestShade(map)
    const darkShade = computeDarkShade(map)

    let rampIndex = 0
    for (let z = 0; z < map.depth; z++) {
      for (let x = 0; x < map.width; x++) {
        const index = z * map.width + x
        const terrain = map.tiles[index]
        // A bridge tile draws the water still running beneath it; the deck
        // above is its own mesh (see bridges.tsx).
        const def = TERRAIN[terrain === "bridge" ? "water" : terrain]
        const jitter = 1 + (rng() - 0.5) * def.jitter
        // Old growth casts a deeper shadow on everything beneath it — sward,
        // road, and the track cut through it alike; feathered so it has no
        // hard rim.
        const canopy = 1 - DARK_WOOD_DARKEN * darkShade[index]
        const ramp = rampAt.get(index)
        // A causeway between two spans stands level at deck height.
        const height = plateaus.has(index) ? TILE_HEIGHT + BRIDGE_RISE : TILE_HEIGHT

        // Box base sits at y=0 and the top at the shared tile height, so tiles
        // sink into the slab and never show a gap from a low camera angle.
        // Full-size footprints: every top face is coplanar with its
        // neighbours, so the ground reads as one continuous surface with no
        // seams or steps; the only visible edge is the optional grid overlay.
        position.set(tileToWorldX(map, x), height / 2, tileToWorldZ(map, z))
        scale.set(1, height, 1)
        matrix.compose(position, quaternion, scale)
        idMesh.setMatrixAt(index, matrix)

        if (ramp) {
          // The wedge climbs along its local +x; yaw that onto the uphill
          // direction. A yaw of θ maps +x to (cos θ, 0, −sin θ), hence −dz.
          rampQuaternion.setFromAxisAngle(up, Math.atan2(-ramp.dz, ramp.dx))
          position.y = 0
          rampMatrix.compose(position, rampQuaternion, unit)
          idRampMesh.setMatrixAt(rampIndex++, rampMatrix)
        }
        const targets = ramp ? 2 : 1

        // Where this tile sits on the forest-shade ramp.
        tint.copy(OPEN_MEADOW_TINT).lerp(DEEP_WOOD_TINT, shade[index])

        if (terrain === "path") {
          // The texture carries the road's colour; the instance carries the
          // weathering from whatever surrounds this stretch, plus the grain.
          const [r, g, b] = roadTint(map, x, z, tier.tier)
          color.setRGB(r, g, b, THREE.SRGBColorSpace)
          color.multiplyScalar(jitter * canopy)
          // Edge data for the ragged verge, in linear space like the rest of
          // the colour pipeline.
          const edge = roadEdge(map, x, z)
          verge.setRGB(edge.verge[0], edge.verge[1], edge.verge[2], THREE.SRGBColorSpace)
          for (let t = 0; t < targets; t++) {
            const target = roadTargets[t]
            const i = target.next++
            target.mesh.setMatrixAt(i, t === RAMP ? rampMatrix : matrix)
            target.mesh.setColorAt(i, color)
            target.overlay.setXYZW(i, tint.r, tint.g, tint.b, def.shadeBlend)
            target.open.setXYZW(i, edge.open[0], edge.open[1], edge.open[2], edge.open[3])
            target.verge.setXYZW(i, verge.r, verge.g, verge.b, edge.vergeGrass)
            target.grass.setX(i, edge.grass)
          }
          continue
        }

        let grass = 0
        let overlayR = 0
        let overlayG = 0
        let overlayB = 0
        let overlayA = 0
        const overlay = SWARD_OVERLAY[terrain]
        if (overlay === undefined) {
          // Flat-coloured ground, pulled along the shade ramp.
          if (def.id === "water") {
            // Water colours by depth — shallow shoreline light, deep water
            // dark. Hand-authored maps carry no depth data and render as
            // shallow.
            const waterDepth = Math.min(
              MAX_WATER_DEPTH,
              Math.max(1, map.water?.depth[index] ?? 1),
            )
            color.copy(waterColors[waterDepth - 1])
          } else if (def.id === "sand") {
            // Beaches fade toward grass as they leave the waterline: full sand
            // against the water, blended a tile out, mostly grass beyond.
            const d = waterDistance(map, x, z)
            const sandiness = d <= 1 ? 1 : d === 2 ? 0.55 : 0.3
            color.copy(grassColor).lerp(sandColor, sandiness)
          } else {
            color.set(def.color)
          }
          color.lerp(tint, def.shadeBlend)
          color.multiplyScalar(jitter * canopy)
        } else {
          // Sward: the texture carries the colour, the instance only the grain.
          // Two layers land on the texture — the tile's own colour at
          // `overlay`, then the shade ramp at `shadeBlend` — folded into one
          // tint and opacity for the shader.
          color.setRGB(1, 1, 1).multiplyScalar(jitter * canopy)
          own.set(def.color)
          const a = overlay
          const b = def.shadeBlend
          const k = 1 - (1 - a) * (1 - b)
          if (k > 0) {
            const wa = (a * (1 - b)) / k
            const wb = b / k
            overlayR = own.r * wa + tint.r * wb
            overlayG = own.g * wa + tint.g * wb
            overlayB = own.b * wa + tint.b * wb
            overlayA = k
          }
          grass = 1
        }
        for (let t = 0; t < targets; t++) {
          const target = groundTargets[t]
          const i = target.next++
          target.mesh.setMatrixAt(i, t === RAMP ? rampMatrix : matrix)
          target.mesh.setColorAt(i, color)
          target.grass.setX(i, grass)
          target.overlay.setXYZW(i, overlayR, overlayG, overlayB, overlayA)
        }
      }
    }

    for (const target of roadTargets) {
      target.mesh.instanceMatrix.needsUpdate = true
      if (target.mesh.instanceColor) target.mesh.instanceColor.needsUpdate = true
      target.open.needsUpdate = true
      target.verge.needsUpdate = true
      target.grass.needsUpdate = true
      target.overlay.needsUpdate = true
    }
    for (const target of groundTargets) {
      target.mesh.instanceMatrix.needsUpdate = true
      if (target.mesh.instanceColor) target.mesh.instanceColor.needsUpdate = true
      target.grass.needsUpdate = true
      target.overlay.needsUpdate = true
    }
    idMesh.instanceMatrix.needsUpdate = true
    idRampMesh.instanceMatrix.needsUpdate = true
  }, [
    map,
    tier,
    roadGeometry,
    groundGeometry,
    roadRampGeometry,
    groundRampGeometry,
    rampAt,
    plateaus,
  ])

  const dirt = useLoader(THREE.TextureLoader, DIRT_TEXTURE_URL)
  useMemo(() => {
    dirt.colorSpace = THREE.SRGBColorSpace
    // Repeat around the cliff, but run the topsoil-to-subsoil ramp just once
    // top to bottom, so wrap horizontally and clamp vertically.
    dirt.wrapS = THREE.RepeatWrapping
    dirt.wrapT = THREE.ClampToEdgeWrapping
    dirt.repeat.set(map.width / 4, 1)
    dirt.anisotropy = 4
  }, [dirt, map])

  const slabPosition = useMemo<[number, number, number]>(
    () => [0, SLAB_TOP - SLAB_THICKNESS / 2, 0],
    [],
  )
  const slabArgs = useMemo<[number, number, number]>(
    () => [map.width + SLAB_EXPAND, SLAB_THICKNESS, map.depth + SLAB_EXPAND],
    [map],
  )

  return (
    <group>
      <mesh position={slabPosition}>
        <boxGeometry args={slabArgs} />
        <meshLambertMaterial map={dirt} />
      </mesh>

      <instancedMesh
        ref={groundMeshRef}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, count - roadCount]}
      >
        <primitive object={groundGeometry} attach="geometry" />
        <primitive object={groundMaterial} attach="material" />
      </instancedMesh>

      <instancedMesh
        ref={roadMeshRef}
        key={tier.id}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, roadCount]}
      >
        <primitive object={roadGeometry} attach="geometry" />
        <primitive object={roadMaterial} attach="material" />
      </instancedMesh>

      {/* Ramps up onto the bridges, in whichever material their tile wears. */}
      <instancedMesh
        ref={groundRampMeshRef}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, groundRampCount]}
      >
        <primitive object={groundRampGeometry} attach="geometry" />
        <primitive object={groundMaterial} attach="material" />
      </instancedMesh>
      <instancedMesh
        ref={roadRampMeshRef}
        key={`ramp-${tier.id}`}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, roadRampCount]}
      >
        <primitive object={roadRampGeometry} attach="geometry" />
        <primitive object={roadMaterial} attach="material" />
      </instancedMesh>

      {/*
        Terrain in the outline pass: ID 0 (black), depth only. It takes no
        outline itself, but its depth stops hidden object seams — say two
        buildings overlapping *behind* a hill — from drawing lines through it.
      */}
      <mesh position={slabPosition} layers-mask={OUTLINE_ID_LAYER_MASK}>
        <boxGeometry args={slabArgs} />
        <meshBasicMaterial color="black" toneMapped={false} />
      </mesh>
      <instancedMesh
        ref={idMeshRef}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, count]}
        layers-mask={OUTLINE_ID_LAYER_MASK}
      >
        <boxGeometry args={[1, 1, 1]} />
        <meshBasicMaterial color="black" toneMapped={false} />
      </instancedMesh>
      <instancedMesh
        ref={idRampMeshRef}
        args={[undefined as unknown as THREE.BufferGeometry, undefined as unknown as THREE.Material, bridges.ramps.length]}
        layers-mask={OUTLINE_ID_LAYER_MASK}
      >
        <primitive object={idRampGeometry} attach="geometry" />
        <meshBasicMaterial color="black" toneMapped={false} />
      </instancedMesh>
    </group>
  )
}
