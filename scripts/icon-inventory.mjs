import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'components/icon-lab/ui-icon-inventory.ts')
async function files(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true })
  return (await Promise.all(entries.map(entry => entry.isDirectory() ? files(`${directory}/${entry.name}`) : `${directory}/${entry.name}`))).flat()
}
/** Read actual imports, including aliases and multiline imports; exclude the catalogue itself. */
export async function iconInventory() {
  const icons = new Map()
  for (const file of (await Promise.all(['app', 'components', 'lib'].map(files))).flat().sort()) {
    if (!/\.tsx?$/.test(file) || file.startsWith('components/icon-lab/') || /\.test\./.test(file)) continue
    const source = ts.createSourceFile(file, await readFile(path.join(root, file), 'utf8'), ts.ScriptTarget.Latest, true)
    for (const node of source.statements) {
      if (!ts.isImportDeclaration(node) || node.moduleSpecifier.text !== 'lucide-react') continue
      const bindings = node.importClause?.namedBindings
      if (!bindings || !ts.isNamedImports(bindings)) continue
      for (const item of bindings.elements) {
        if (item.isTypeOnly || node.importClause.isTypeOnly) continue
        const name = (item.propertyName ?? item.name).text.replace(/Icon$/, '')
        const uses = icons.get(name) ?? new Set(); uses.add(file); icons.set(name, uses)
      }
    }
  }
  const lucide = [...icons].sort(([a], [b]) => a.localeCompare(b)).map(([name, uses]) => ({ id: `ui-${name}`, name, label: name.replace(/([a-z\d])([A-Z])/g, '$1 $2'), sources: [...uses] }))
  const artwork = (await files('public/game-icons')).filter(file => file.endsWith('.svg')).sort().map(file => ({
    id: `svg-${path.basename(file, '.svg')}`, label: path.basename(file, '.svg').replace(/^./, c => c.toUpperCase()), url: file.slice('public'.length), sources: [file],
  }))
  artwork.push({ id: 'svg-app', label: 'App icon', url: '/icon.svg', sources: ['app/layout.tsx', 'public/icon.svg'] })
  for (const [name, label] of [['favicon.ico', 'Browser favicon'], ['apple-icon.png', 'Apple app icon'], ['icon-192.png', 'App icon · 192'], ['icon-512.png', 'App icon · 512'], ['icon-maskable-512.png', 'Maskable app icon']]) {
    artwork.push({ id: `app-${name}`, label, url: `/${name}`, sources: [`public/${name}`] })
  }
  return { lucide, artwork }
}
export function inventorySource({ lucide, artwork }) {
  return `// Generated by node scripts/icon-inventory.mjs from application imports and public/game-icons.\nimport { ${lucide.map(icon => icon.name).join(', ')} } from "lucide-react"\n\nexport const UI_ICONS = [\n${lucide.map(({name,...icon}) => `  { ...${JSON.stringify(icon)}, component: ${name} },`).join('\n')}\n]\n\nexport const SVG_ICONS = ${JSON.stringify(artwork, null, 2)}\n`
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = inventorySource(await iconInventory())
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== source) throw new Error('UI icon inventory is stale. Run node scripts/icon-inventory.mjs')
    console.log('UI icon inventory matches application sources.')
  } else { await writeFile(output, source); console.log(`Updated ${path.relative(root, output)}`) }
}
