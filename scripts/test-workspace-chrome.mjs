import assert from "node:assert/strict"
import { chromium } from "playwright"

// Exercise real playground routes and renderers; no separate demo or test app.
const base = process.env.BENCH_URL ?? "http://localhost:3100"
const browser = await chromium.launch({ channel:"chromium", headless:true, args:process.platform === "darwin" ? ["--use-angle=metal"] : [] })
const errors = []
try {
  const page = await browser.newPage({ viewport:{width:1440,height:900} })
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(`${base}/assets`, {timeout:120000})
  await page.getByRole("button",{name:"Characters",exact:true}).click()
  const story = page.getByRole("button",{name:"Storybook",exact:true})
  await story.waitFor({timeout:120000})
  await page.getByRole("button",{name:"Open Storybook",exact:true}).waitFor()
  assert.equal(await page.getByRole("button",{name:/^Open /}).count(),await page.locator('.chrome-entity-list button').count(),"grid contains every character")
  assert.ok(await page.locator('.chrome-entity-grid canvas').evaluateAll(cs=>new Set(cs.map(c=>c.dataset.sequence)).size>1),"grid varies sprite sequences")
  await page.getByRole("button",{name:"Open Storybook",exact:true}).click()
  const head = page.getByRole("slider",{name:"Head size",exact:true})
  await head.waitFor()
  const before = await head.getAttribute("aria-valuenow")
  await head.focus(); await page.keyboard.press("ArrowLeft")
  assert.notEqual(await head.getAttribute("aria-valuenow"),before,"keyboard slider changes a property")
  const edited = await head.getAttribute("aria-valuenow")
  await page.getByRole("combobox",{name:"Body type",exact:true}).click()
  await page.getByRole("option",{name:"Female",exact:true}).click()
  assert.match(await page.getByRole("combobox",{name:"Body type",exact:true}).innerText(),/Female/)
  await page.getByRole("checkbox",{name:"Show rig",exact:true}).check()
  await page.getByRole("combobox",{name:"Selected rig joint",exact:true}).waitFor()
  assert.ok(await page.locator('.chrome-inspector-content .person-rig-inspector').isVisible())
  await page.getByRole("checkbox",{name:"Show rig",exact:true}).uncheck()
  await page.getByRole("button",{name:"Hide properties",exact:true}).click()
  await page.getByRole("button",{name:"Show properties",exact:true}).click()
  const separator = page.getByRole("separator",{name:"Resize navigation",exact:true})
  const navBefore = await page.locator('.chrome-navigation').boundingBox()
  const box = await separator.boundingBox()
  await page.mouse.move(box.x,box.y+200); await page.mouse.down(); await page.mouse.move(box.x+55,box.y+200,{steps:8}); await page.mouse.up()
  const navAfter = await page.locator('.chrome-navigation').boundingBox()
  assert.ok(navAfter.width > navBefore.width+30,"navigation resizes independently")
  await page.getByRole("button",{name:"Toggle light mode",exact:true}).click()
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
  assert.equal(await page.locator('.chrome-canvas-content').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(85, 104, 53)',"light mode keeps game grass")
  await page.getByRole("button",{name:"Files",exact:true}).click()
  await page.getByRole("button",{name:"Copy / paste JSON",exact:true}).click()
  await page.getByRole("dialog").waitFor()
  assert.ok(await page.getByRole("textbox",{name:"Character edits JSON"}).evaluate(el=>el === document.activeElement))
  await page.keyboard.press("Escape")
  assert.equal(await page.getByRole("dialog").count(),0)
  await page.getByRole("button",{name:"Workspace",exact:true}).click()
  await page.getByRole("button",{name:"Characters",exact:true}).click()
  assert.equal(await head.getAttribute("aria-valuenow"),edited,"back navigation retains the edited draft")
  await page.getByRole("textbox",{name:"Search entities"}).fill("Storybook")
  await page.waitForFunction(()=>{const c=document.querySelector('canvas[data-sprite-id="preset/Storybook"]');return c && Array.from(c.getContext('2d').getImageData(0,0,16,16).data).some((x,i)=>i%4===3&&x>0)},{},{timeout:120000})
  const sprite = page.locator('canvas[data-sprite-id="preset/Storybook"]')
  await page.mouse.move(700,100)
  const idle = await sprite.evaluate(c=>c.toDataURL())
  await story.hover()
  await page.waitForFunction(idle=>document.querySelector('.chrome-navigation canvas[data-sprite-id="preset/Storybook"]')?.toDataURL() !== idle,idle,{timeout:120000})
  assert.notEqual(await sprite.evaluate(c=>c.toDataURL()),idle,"hover plays the actual walk sprite")
  await page.mouse.move(700,100); await page.waitForTimeout(100)
  assert.equal(await sprite.evaluate(c=>c.toDataURL()),idle,"leaving restores the idle sprite")
  await page.emulateMedia({reducedMotion:"reduce"}); await story.hover(); await page.waitForTimeout(250)
  assert.equal(await sprite.evaluate(c=>c.toDataURL()),idle,"reduced motion leaves sprites idle")
  await page.setViewportSize({width:390,height:844})
  await page.getByRole("button",{name:"Show navigation",exact:true}).click()
  await page.getByRole("dialog",{name:"Navigation",exact:true}).waitFor()
  await page.getByRole("textbox",{name:"Search entities"}).fill("Female")
  await page.getByRole("button",{name:"Female",exact:true}).click()
  assert.equal(await page.getByRole("dialog").isVisible(),false,"selecting an entity closes the mobile drawer")
  await page.getByRole("button",{name:"Show properties",exact:true}).click()
  await page.getByRole("dialog",{name:"Properties",exact:true}).waitFor()
  const propertyLabel = page.getByRole("combobox",{name:"Body type",exact:true})
  assert.ok(await propertyLabel.evaluate(el=>el.getBoundingClientRect().width>200),"mobile fields fill the property column")
  await page.keyboard.press("Escape")
  await page.setViewportSize({width:1440,height:900})
  await page.goto(`${base}/assets?asset=buildings`, {timeout:120000})
  await page.getByRole("button",{name:"Open Tavern",exact:true}).waitFor({timeout:120000})
  assert.equal(await page.locator('.chrome-entity-grid button').count(),await page.locator('.chrome-entity-list button').count(),"grid contains every building")
  await page.getByRole("button",{name:"Open Tavern",exact:true}).click()
  await page.getByRole("button",{name:"Hide properties",exact:true}).waitFor()
  assert.equal(await page.locator('.chrome-canvas-header h1').innerText(),"Tavern")
  assert.deepEqual(errors,[])
  console.log("Workspace chrome passed: selection, keyboard inputs, rig, resizing, themes, JSON dialog, draft retention, sprites, mobile drawers")
} finally { await browser.close() }
