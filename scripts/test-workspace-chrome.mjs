import assert from "node:assert/strict"
import { chromium } from "playwright"

// Exercise real playground routes and renderers; no separate demo or test app.
const base = process.env.BENCH_URL ?? "http://localhost:3100"
const browser = await chromium.launch({ channel:"chromium", headless:true, args:process.platform === "darwin" ? ["--use-angle=metal"] : [] })
const errors = []
try {
  const page = await browser.newPage({ viewport:{width:1440,height:900} })
  page.on("pageerror", error => errors.push(error.stack ?? error.message))
  await page.goto(`${base}/assets`, {timeout:120000})
  await page.getByRole("button",{name:"Characters",exact:true}).click()
  const story = page.getByRole("button",{name:"Storybook",exact:true})
  await story.waitFor({timeout:120000})
  await page.getByRole("button",{name:"Open Storybook",exact:true}).waitFor()
  assert.equal(await page.getByRole("button",{name:/^Open /}).count(),await page.locator('.chrome-entity-list button').count(),"staging map contains every character")
  await page.locator('.chrome-staging-map canvas').waitFor()
  await page.waitForTimeout(2000)
  const positions = () => page.locator('.chrome-staging-label').evaluateAll(items => items.slice(0,2).map(item => {const r=item.getBoundingClientRect();return {x:r.x,y:r.y,worldX:item.dataset.worldX,worldZ:item.dataset.worldZ}}))
  const initial = await positions()
  await page.mouse.move(900,450); await page.mouse.wheel(0,-120); await page.waitForTimeout(300)
  const zoomed = await positions()
  const distance = points => Math.hypot(points[1].x-points[0].x,points[1].y-points[0].y)
  assert.ok(Math.abs(distance(zoomed)/distance(initial)-Math.exp(.18))<.03,"staging wheel uses game zoom sensitivity")
  await page.mouse.move(900,780); await page.mouse.down(); await page.mouse.move(980,800,{steps:8}); await page.mouse.up(); await page.waitForTimeout(200)
  const panned = await positions()
  assert.ok(panned[0].x>zoomed[0].x+60,"drag pans the map")
  assert.deepEqual(panned.map(p=>[p.worldX,p.worldZ]),initial.map(p=>[p.worldX,p.worldZ]),"animation and camera movement leave asset world positions fixed")
  assert.equal(await page.getByRole("combobox",{name:/zoom/i}).count(),0,"zoom dropdowns are removed")
  await page.getByRole("button",{name:"Hide navigation",exact:true}).click(); await page.waitForTimeout(300)
  const expanded = await positions()
  assert.ok(Math.abs(distance(expanded)/distance(panned)-1)<.02,"collapsing a sidebar preserves the user's zoom")
  await page.getByRole("button",{name:"Show navigation",exact:true}).click(); await page.waitForTimeout(300)
  const restored = await positions()
  assert.ok(Math.abs(restored[0].x-panned[0].x)<3 && Math.abs(restored[0].y-panned[0].y)<3,"restoring a sidebar retains the camera's pan")
  await page.getByRole("button",{name:"Open Storybook",exact:true}).click()
  await page.getByRole("combobox",{name:"Preview view",exact:true}).click()
  await page.getByRole("option",{name:"Native size",exact:true}).click()
  const figure = page.locator('.person-stage-native .person-native [role=img]').first()
  await figure.waitFor({timeout:120000})
  assert.equal(Math.round((await figure.boundingBox()).width),64,"native inspection uses actual atlas pixels")
  const stageBox = await page.locator('.person-stage-native').boundingBox()
  await page.mouse.move(stageBox.x+stageBox.width/2,stageBox.y+stageBox.height/2)
  await page.mouse.wheel(0,-120)
  const enlarged = figure
  await enlarged.waitFor()
  const wheelWidth = (await enlarged.boundingBox()).width
  assert.ok(Math.abs(wheelWidth/64-Math.exp(.18))<.03,"native inspection uses the shared wheel response")
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:2})
  const x=stageBox.x+stageBox.width/2, y=stageBox.y+stageBox.height/2
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:x-30,y},{id:2,x:x+30,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{id:1,x:x-60,y},{id:2,x:x+60,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await page.waitForTimeout(200)
  assert.ok(Math.abs((await enlarged.boundingBox()).width/wheelWidth-2)<.05,"two-finger pinch zoom works in sprite inspectors")
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false}); await cdp.detach()
  await page.getByRole('combobox',{name:'Preview view',exact:true}).click()
  await page.getByRole('option',{name:'Character',exact:true}).click()
  const head = page.getByRole("slider",{name:"Head size",exact:true})
  await head.waitFor()
  const before = await head.getAttribute("aria-valuenow")
  await head.focus(); await page.keyboard.press("ArrowLeft")
  assert.notEqual(await head.getAttribute("aria-valuenow"),before,"keyboard slider changes a property")
  const edited = await head.getAttribute("aria-valuenow")
  await page.getByRole("combobox",{name:"Body type",exact:true}).click()
  await page.getByRole("option",{name:"Female",exact:true}).click()
  assert.match(await page.getByRole("combobox",{name:"Body type",exact:true}).innerText(),/Female/)
  await page.getByRole("checkbox",{name:"Show rig",exact:true}).check()
  await page.getByRole("combobox",{name:"Selected rig joint",exact:true}).waitFor()
  assert.ok(await page.locator('.chrome-inspector-content .person-rig-inspector').isVisible())
  await page.getByRole("checkbox",{name:"Show rig",exact:true}).uncheck()
  await page.getByRole("button",{name:"Hide properties",exact:true}).click()
  await page.getByRole("button",{name:"Show properties",exact:true}).click()
  const separator = page.getByRole("separator",{name:"Resize navigation",exact:true})
  const navBefore = await page.locator('.chrome-navigation').boundingBox()
  const box = await separator.boundingBox()
  await page.mouse.move(box.x,box.y+200); await page.mouse.down(); await page.mouse.move(box.x+55,box.y+200,{steps:8}); await page.mouse.up()
  const navAfter = await page.locator('.chrome-navigation').boundingBox()
  assert.ok(navAfter.width > navBefore.width+30,"navigation resizes independently")
  await page.getByRole("button",{name:"Toggle light mode",exact:true}).click()
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
  assert.equal(await page.locator('.chrome-canvas-content').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(85, 104, 53)',"light mode keeps game grass")
  await page.getByRole("button",{name:"Files",exact:true}).click()
  await page.getByRole("button",{name:"Copy / paste JSON",exact:true}).click()
  await page.getByRole("dialog").waitFor()
  assert.ok(await page.getByRole("textbox",{name:"Character edits JSON"}).evaluate(el=>el === document.activeElement))
  await page.keyboard.press("Escape")
  assert.equal(await page.getByRole("dialog").count(),0)
  await page.getByRole("button",{name:"Workspace",exact:true}).click()
  await page.getByRole("button",{name:"Characters",exact:true}).click()
  assert.equal(await head.getAttribute("aria-valuenow"),edited,"back navigation retains the edited draft")
  await page.getByRole("textbox",{name:"Search entities"}).fill("Storybook")
  await page.waitForFunction(()=>{const c=document.querySelector('canvas[data-sprite-id="preset/Storybook"]');return c && Array.from(c.getContext('2d').getImageData(0,0,16,16).data).some((x,i)=>i%4===3&&x>0)},{},{timeout:120000})
  const sprite = page.locator('canvas[data-sprite-id="preset/Storybook"]')
  await page.mouse.move(700,100)
  const idle = await sprite.evaluate(c=>c.toDataURL())
  await story.hover()
  await page.waitForFunction(idle=>document.querySelector('.chrome-navigation canvas[data-sprite-id="preset/Storybook"]')?.toDataURL() !== idle,idle,{timeout:120000})
  assert.notEqual(await sprite.evaluate(c=>c.toDataURL()),idle,"hover plays the actual walk sprite")
  await page.mouse.move(700,100); await page.waitForTimeout(100)
  assert.equal(await sprite.evaluate(c=>c.toDataURL()),idle,"leaving restores the idle sprite")
  await page.emulateMedia({reducedMotion:"reduce"}); await story.hover(); await page.waitForTimeout(250)
  assert.equal(await sprite.evaluate(c=>c.toDataURL()),idle,"reduced motion leaves sprites idle")
  await page.setViewportSize({width:390,height:844})
  await page.getByRole("button",{name:"Show navigation",exact:true}).click()
  await page.getByRole("dialog",{name:"Navigation",exact:true}).waitFor()
  await page.getByRole("textbox",{name:"Search entities"}).fill("Female")
  await page.getByRole("button",{name:"Female",exact:true}).click()
  assert.equal(await page.getByRole("dialog").isVisible(),false,"selecting an entity closes the mobile drawer")
  await page.getByRole("button",{name:"Show properties",exact:true}).click()
  await page.getByRole("dialog",{name:"Properties",exact:true}).waitFor()
  const propertyLabel = page.getByRole("combobox",{name:"Body type",exact:true})
  assert.ok(await propertyLabel.evaluate(el=>el.getBoundingClientRect().width>200),"mobile fields fill the property column")
  await page.keyboard.press("Escape")
  await page.setViewportSize({width:1440,height:900})
  await page.goto(`${base}/assets?asset=buildings`, {timeout:120000})
  await page.getByRole("button",{name:"Open Tavern",exact:true}).waitFor({timeout:120000})
  assert.equal(await page.locator('.chrome-staging-label').count(),await page.locator('.chrome-entity-list button').count(),"staging map contains every building")
  await page.getByRole("button",{name:"Open Tavern",exact:true}).click()
  await page.getByRole("button",{name:"Hide properties",exact:true}).waitFor()
  assert.equal(await page.locator('.chrome-canvas-header h1').innerText(),"Tavern")
  await page.emulateMedia({reducedMotion:"no-preference"})
  await page.goto(`${base}/changelog`,{timeout:120000})
  const links = page.locator('.chrome-entity-list a')
  await links.first().waitFor()
  assert.equal(await page.locator('.workspace-content-scroll').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(241, 241, 232)',"documents use the light chrome surface")
  const destination = links.nth(8), hash = await destination.getAttribute('href')
  await destination.click()
  await page.waitForTimeout(50)
  const during = await page.locator('.workspace-content-scroll').evaluate(el=>el.scrollTop)
  assert.ok(during>0,"anchor navigation scrolls visibly")
  await page.waitForFunction(hash => document.querySelector(`.chrome-entity-list a[href="${hash}"]`)?.getAttribute('aria-current') === 'location',hash)
  assert.equal(new URL(page.url()).hash,hash,"section links are real anchors")
  await page.locator('.workspace-content-scroll').evaluate(el=>el.scrollTo({top:0,behavior:'instant'}))
  await page.waitForFunction(()=>document.querySelector('.chrome-entity-list a')?.getAttribute('aria-current')==='location')
  await page.locator('.workspace-content-scroll').evaluate(el=>el.scrollTop=100)
  await page.waitForFunction(()=>document.querySelector('.workspace-content-scroll')?.dataset.scrolling==='true')
  await page.waitForFunction(()=>!document.querySelector('.workspace-content-scroll')?.dataset.scrolling)
  await page.getByRole("button",{name:"Toggle light mode",exact:true}).click()
  assert.equal(await page.locator('.workspace-content-scroll').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(23, 24, 16)',"documents use the dark chrome surface")
  await page.goto(`${base}/assets?asset=pipeline`,{timeout:120000})
  await page.locator('.workspace-content-scroll').waitFor({timeout:120000})
  assert.equal(await page.locator('.workspace-content-scroll').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(23, 24, 16)',"pipeline uses the document surface")
  await page.goto(`${base}/assets`,{timeout:120000})
  assert.equal(await page.getByRole('button',{name:'Rendering',exact:true}).count(),0,"Rendering is removed")
  await page.goto(`${base}/assets?asset=maps`,{timeout:120000})
  const connections = page.getByRole('checkbox',{name:'Show connections',exact:true})
  await connections.waitFor({timeout:120000})
  assert.ok(await connections.evaluate(el=>parseFloat(getComputedStyle(el.closest('label')).fontSize)>0),"toolbar checkbox labels remain visible")
  assert.deepEqual(errors,[])
  console.log("Workspace chrome passed: staging pan/zoom, retained camera framing, native sprite sizing, touch pinch, selection, keyboard inputs, rig, resizing, themes, JSON dialog, draft retention, sprites, mobile drawers, document anchors/scroll tracking, scrollbars, pipeline, retired Rendering")
} finally { await browser.close() }
